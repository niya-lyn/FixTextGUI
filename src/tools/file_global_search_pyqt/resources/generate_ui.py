import os
import glob
import subprocess
import sys

# ================= 配置区域 =================
TARGET_API = os.environ.get("QT_API", "pyqt5").lower()

print(f"=== 当前目标后端: {TARGET_API} ===")

# 根据目标版本配置命令
if TARGET_API == "pyside6":
    RCC_CMD = ["pyside6-rcc"]
    UIC_CMD_PREFIX = ["pyside6-uic"]

elif TARGET_API == "pyqt5":
    RCC_CMD = ["pyrcc5"]
    UIC_CMD_PREFIX = [sys.executable, "-m", "PyQt5.uic.pyuic"]

elif TARGET_API == "pyqt6":
    RCC_CMD = ["pyqt6-rcc"]
    UIC_CMD_PREFIX = ["pyqt6-uic"]

else:
    print(f"错误: 不支持的 QT_API: {TARGET_API}")
    exit(1)
# ===========================================

# 设置路径
current_dir = os.path.dirname(os.path.abspath(__file__))
os.chdir(current_dir)

# --- 1. 编译资源文件 (resources.qrc) ---
print(f"--- 开始编译资源文件 resources.qrc [{TARGET_API}] ---")

rcc_args = RCC_CMD + ["resources.qrc", "-o", "resources_rc.py"]

try:
    subprocess.run(rcc_args, check=True)
    print("--- resources.qrc 已成功编译！ ---")
except subprocess.CalledProcessError:
    print(f"错误: 资源文件编译失败。请确保已安装 {TARGET_API} 并且命令工具在 PATH 中。")
    exit(1)
except FileNotFoundError:
    print(f"错误: 找不到命令 {RCC_CMD[0]}。请检查是否已安装对应库 (pip install {TARGET_API})。")
    exit(1)


# --- 2. 编译 UI 文件 ---
SOURCE_DIR = "./ui"
TARGET_DIR = "./ui_generated"

print("--- 开始生成 UI 的 Python 代码 ---")

# 创建目标目录和初始化文件
os.makedirs(TARGET_DIR, exist_ok=True)

with open(os.path.join(TARGET_DIR, "__init__.py"), "w") as f:
    f.write(f"# Generated by build script for {TARGET_API}\n")

# 检查.ui文件是否存在
ui_files = glob.glob(os.path.join(SOURCE_DIR, "*.ui"))
if not ui_files:
    print(f"警告: 在 '{SOURCE_DIR}' 目录中没有找到任何 .ui 文件。脚本执行结束。")
    exit(0)

# 清理旧文件
print("正在清理旧文件...")
for old_file in glob.glob(os.path.join(TARGET_DIR, "ui_*.py")):
    try:
        os.remove(old_file)
    except OSError:
        pass

# 处理每个 UI 文件
for ui_file in ui_files:
    filename = os.path.basename(ui_file)
    base_name = os.path.splitext(filename)[0]
    output_file = os.path.join(TARGET_DIR, f"ui_{base_name}.py")

    print(f"正在转换: '{ui_file}'  ==>  '{output_file}'")

    cmd = UIC_CMD_PREFIX + [ui_file, "-o", output_file]

    try:
        subprocess.run(cmd, check=True)

    except subprocess.CalledProcessError:
        print(f"错误: 转换文件 {ui_file} 失败")
        exit(1)
    except FileNotFoundError:
        print(f"错误: 找不到 UI 编译工具 {UIC_CMD_PREFIX[0]}")
        exit(1)

print(f"--- 所有 UI 文件均已成功生成 (Target: {TARGET_API})！ ---")
